  const PREFIXES = ["Filtros de foco ativos em", "Bloqueado em", "Ver itens do grupo (", "Tag Steam API:", "Consumido:", "Limite:", "Tokens:"];
  const ATTRS = ["placeholder", "title", "aria-label"];
  let lang = "pt-BR";
  const roots = new Set();
  const original = new WeakMap(); // node -> pt text
  const shown = new WeakMap(); // node -> text we wrote

  function col() {
    return lang === "en-US" ? 0 : lang === "zh-Hans" ? 1 : lang === "zh-Hant" ? 2 : -1;
  }

  function t(text) {
    const i = col();
    if (i < 0 || !text) return text;
    const key = String(text).trim();
    if (!key) return text;
    const e = DICT[key];
    if (e) return String(text).replace(key, e[i]);
    for (const p of PREFIXES) {
      if (key.startsWith(p) && DICT[p]) return String(text).replace(p, DICT[p][i]);
    }
    return text;
  }

  function applyText(node) {
    const cur = node.nodeValue;
    if (shown.get(node) !== cur) original.set(node, cur);
    const src = original.get(node);
    const out = t(src);
    if (out !== cur) {
      shown.set(node, out);
      node.nodeValue = out;
    } else {
      shown.set(node, cur);
    }
  }

  function applyAttrs(el) {
    if (!el.getAttribute) return;
    for (const a of ATTRS) {
      const v = el.getAttribute(a);
      if (v == null) continue;
      const k = "data-chronos-i18n-" + a;
      let src = el.getAttribute(k);
      if (src == null || (el.getAttribute(k + "-shown") !== v)) {
        src = v;
        el.setAttribute(k, v);
      }
      const out = t(src);
      el.setAttribute(k + "-shown", out);
      if (out !== v) el.setAttribute(a, out);
    }
  }

  function translateTree(root) {
    if (!root) return;
    const doc = root.ownerDocument || root;
    if (!doc.createTreeWalker) return;
    const walker = doc.createTreeWalker(root, 1 | 4);
    let n = walker.currentNode;
    while (n) {
      if (n.nodeType === 3) {
        const p = n.parentNode;
        if (!p || !/^(SCRIPT|STYLE)$/.test(p.nodeName)) applyText(n);
      } else if (n.nodeType === 1) {
        applyAttrs(n);
      }
      n = walker.nextNode();
    }
  }

  function observe(root) {
    if (!root || roots.has(root)) return;
    roots.add(root);
    translateTree(root);
    if (typeof MutationObserver === "undefined") return;
    new MutationObserver((muts) => {
      for (const m of muts) {
        if (m.type === "characterData") applyText(m.target);
        else if (m.type === "attributes") applyAttrs(m.target);
        else m.addedNodes.forEach((a) => (a.nodeType === 3 ? applyText(a) : translateTree(a)));
      }
    }).observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }

  function setLang(next) {
    const v = String(next || "pt-BR");
    if (v === lang) return;
    lang = v;
    roots.forEach((r) => translateTree(r));
  }

  g.ChronosI18n = { t, setLang, observe, translateTree, getLang: () => lang, _dict: DICT };
  if (typeof module !== "undefined" && module.exports) module.exports = g.ChronosI18n;
